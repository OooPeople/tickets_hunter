#!/usr/bin/env python3
"""Execute one declarative negative probe and preserve its real child transcript.

The probe request is a concrete, digest-pinned input generated by a reviewed
family harness.  This runner never accepts a shell command.  It executes one
repository Python producer (or pytest itself), captures that child's exact
stdout/stderr/exit code, and writes a strict report before returning the same
non-zero exit code.  ``run_utiki_evidence.py`` then seals that report in the
per-execution-key evidence envelope.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath
from typing import Any

try:
    from tools.utiki_negative_contract import (
        NegativeContractError,
        validate_request_contract,
    )
except ModuleNotFoundError:  # Direct execution from tools/.
    from utiki_negative_contract import (  # type: ignore[no-redef]
        NegativeContractError,
        validate_request_contract,
    )


SCHEMA_VERSION = 1
SHA256_RE = re.compile(r"[0-9a-f]{64}")


class ProbeError(Exception):
    pass


def _strict_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ProbeError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def _load(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(
            path.read_text(encoding="utf-8"), object_pairs_hook=_strict_object
        )
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ProbeError(f"cannot read probe JSON: {path}") from exc
    if not isinstance(value, dict):
        raise ProbeError("probe JSON root must be an object")
    return value


def _exact(value: dict[str, Any], expected: set[str], label: str) -> None:
    if set(value) != expected:
        raise ProbeError(f"{label} fields mismatch")


def _sha256(path: Path) -> str:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError as exc:
        raise ProbeError(f"cannot digest {path}") from exc


def _safe_relative(value: Any, label: str) -> str:
    if not isinstance(value, str) or not value or "\\" in value or "\x00" in value:
        raise ProbeError(f"{label} is invalid")
    path = PurePosixPath(value)
    if path.is_absolute() or ".." in path.parts or str(path) != value:
        raise ProbeError(f"{label} is unsafe")
    return value


def _safe_file(root: Path, value: Any, digest: Any, label: str) -> Path:
    relative = _safe_relative(value, label)
    path = (root / relative).resolve()
    if root not in path.parents or path.is_symlink() or not path.is_file():
        raise ProbeError(f"{label} is not a regular file inside the probe directory")
    if not isinstance(digest, str) or SHA256_RE.fullmatch(digest) is None:
        raise ProbeError(f"{label} digest is invalid")
    if _sha256(path) != digest:
        raise ProbeError(f"{label} digest mismatch")
    return path


def _expand_probe_path(root: Path, value: str, *, label: str) -> str:
    marker = "{PROBE_ROOT}"
    if value == marker:
        return str(root)
    prefix = marker + "/"
    if not value.startswith(prefix):
        return value
    relative = _safe_relative(value[len(prefix) :], label)
    path = (root / relative).resolve()
    if root not in path.parents:
        raise ProbeError(f"{label} escapes the probe directory")
    return str(path)


def _require_isolation(proof: Path | None, request: dict[str, Any]) -> dict[str, Any] | None:
    environment = request["environment"]
    if environment == "host":
        if proof is not None:
            raise ProbeError("host probe may not claim an isolation proof")
        return None
    if environment != "isolated":
        raise ProbeError("unknown probe environment")
    if os.environ.get("TICKETS_HUNTER_HARD_EGRESS_ACTIVE") != "1":
        raise ProbeError("isolated negative probe cannot run on the host")
    if proof is None:
        raise ProbeError("isolated negative probe requires an isolation proof")
    payload = _load(proof)
    if (
        payload.get("schema_version") != 1
        or payload.get("status") != "PASS"
        or payload.get("network_mode") != "none"
        or payload.get("candidate_sha") != request["candidate_sha"]
    ):
        raise ProbeError("isolation proof does not bind this isolated run")
    return {
        "path": str(proof.resolve()),
        "sha256": _sha256(proof),
    }


def _registry_entry(registry_path: Path, request: dict[str, Any]) -> dict[str, Any]:
    registry = _load(registry_path)
    _exact(
        registry,
        {
            "schema_version",
            "registry_id",
            "phase",
            "catalog_id",
            "catalog_revision",
            "catalog_sha256",
            "probes",
        },
        "negative probe registry",
    )
    if (
        registry["schema_version"] != 1
        or registry["registry_id"] != "utiki-p1-negative-probes"
        or registry["phase"] != "P1"
    ):
        raise ProbeError("negative probe registry identity is invalid")
    raw_probes = registry["probes"]
    if not isinstance(raw_probes, list):
        raise ProbeError("negative probe registry probes must be an array")
    key_names = ("case_id", "obligation_id", "variant_id", "job_id", "target")
    requested_key = tuple(request[name] for name in key_names)
    matches: list[dict[str, Any]] = []
    seen: set[tuple[Any, ...]] = set()
    for index, value in enumerate(raw_probes):
        if not isinstance(value, dict):
            raise ProbeError(f"registry probes[{index}] is not an object")
        _exact(
            value,
            {
                "argument_contract",
                *key_names,
                "environment",
                "mutation",
                "payload_contract",
                "rejection_token",
                "child_kind",
                "child_producer",
                "input_kinds",
            },
            f"registry probes[{index}]",
        )
        key = tuple(value[name] for name in key_names)
        if key in seen:
            raise ProbeError("negative probe registry contains a duplicate key")
        seen.add(key)
        if key == requested_key:
            matches.append(value)
    if len(matches) != 1:
        raise ProbeError("probe request is not uniquely reviewed in the registry")
    entry = matches[0]
    child = request["child"]
    raw_inputs = request["inputs"]
    actual_input_kinds = sorted(
        item.get("kind") for item in raw_inputs if isinstance(item, dict)
    )
    if (
        request["environment"] != entry["environment"]
        or request["mutation"] != entry["mutation"]
        or request["rejection_token"] != entry["rejection_token"]
        or child.get("kind") != entry["child_kind"]
        or child.get("producer") != entry["child_producer"]
        or actual_input_kinds != sorted(entry["input_kinds"])
    ):
        raise ProbeError("probe request differs from its reviewed registry entry")
    return entry


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository-root", type=Path, required=True)
    parser.add_argument("--probe-registry", type=Path, required=True)
    parser.add_argument("--probe-input", type=Path, required=True)
    parser.add_argument("--producer-report", type=Path, required=True)
    parser.add_argument("--isolation-proof", type=Path)
    return parser


def main(argv: list[str] | None = None) -> int:
    arguments = _parser().parse_args(argv)
    try:
        repository = arguments.repository_root.resolve(strict=True)
        probe_input = arguments.probe_input.resolve(strict=True)
        probe_root = probe_input.parent
        request = _load(probe_input)
        _exact(
            request,
            {
                "schema_version",
                "case_id",
                "obligation_id",
                "variant_id",
                "job_id",
                "target",
                "candidate_sha",
                "environment",
                "mutation",
                "rejection_token",
                "child",
                "inputs",
            },
            "probe input",
        )
        if request["schema_version"] != SCHEMA_VERSION:
            raise ProbeError("unknown probe input schema")
        registry_entry = _registry_entry(
            arguments.probe_registry.resolve(strict=True), request
        )
        validate_request_contract(
            registry_entry,
            request,
            probe_root=probe_root,
            repository_root=repository,
        )
        token = request["rejection_token"]
        if not isinstance(token, str) or not token:
            raise ProbeError("probe rejection token is invalid")
        isolation = _require_isolation(arguments.isolation_proof, request)

        child = request["child"]
        if not isinstance(child, dict):
            raise ProbeError("child definition must be an object")
        _exact(child, {"kind", "producer", "arguments", "working_directory"}, "child")
        child_kind = child["kind"]
        producer = child["producer"]
        raw_arguments = child["arguments"]
        if not isinstance(raw_arguments, list) or any(
            not isinstance(item, str) or not item for item in raw_arguments
        ):
            raise ProbeError("child arguments are invalid")
        expanded_arguments = [
            _expand_probe_path(probe_root, item, label="child argument")
            for item in raw_arguments
        ]
        raw_working_directory = child["working_directory"]
        if raw_working_directory is None:
            child_working_directory = repository
        elif isinstance(raw_working_directory, str):
            expanded = _expand_probe_path(
                probe_root, raw_working_directory, label="child working directory"
            )
            child_working_directory = Path(expanded).resolve()
            if (
                child_working_directory != probe_root
                and probe_root not in child_working_directory.parents
                or child_working_directory.is_symlink()
                or not child_working_directory.is_dir()
            ):
                raise ProbeError("child working directory is not inside the probe directory")
        else:
            raise ProbeError("child working directory is invalid")
        if child_kind == "repository-python":
            producer_relative = _safe_relative(producer, "child producer")
            producer_path = (repository / producer_relative).resolve()
            if (
                repository not in producer_path.parents
                or producer_path.is_symlink()
                or not producer_path.is_file()
            ):
                raise ProbeError("child producer is not a repository file")
            command = [sys.executable, str(producer_path), *expanded_arguments]
            producer_digest = _sha256(producer_path)
        elif child_kind == "pytest-module":
            if producer != "pytest":
                raise ProbeError("pytest child producer must be the pytest module")
            command = [sys.executable, "-m", "pytest", *expanded_arguments]
            producer_digest = hashlib.sha256(b"python-module:pytest").hexdigest()
        else:
            raise ProbeError("unsupported child kind")

        concrete_inputs: list[dict[str, str]] = []
        raw_inputs = request["inputs"]
        if not isinstance(raw_inputs, list) or not raw_inputs:
            raise ProbeError("negative probe has no concrete child inputs")
        for index, item in enumerate(raw_inputs):
            if not isinstance(item, dict):
                raise ProbeError("negative probe input entry is invalid")
            _exact(item, {"kind", "path", "sha256"}, f"inputs[{index}]")
            path = _safe_file(probe_root, item["path"], item["sha256"], f"inputs[{index}]")
            if str(path) not in command:
                raise ProbeError("child command does not consume a concrete mutation input")
            concrete_inputs.append(
                {"kind": item["kind"], "path": str(path), "sha256": item["sha256"]}
            )

        completed = subprocess.run(
            command,
            cwd=child_working_directory,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
        report_path = arguments.producer_report.resolve()
        report_path.parent.mkdir(parents=True, exist_ok=True)
        stem = report_path.stem
        stdout_path = report_path.with_name(f"{stem}.child.stdout")
        stderr_path = report_path.with_name(f"{stem}.child.stderr")
        stdout_path.write_bytes(completed.stdout)
        stderr_path.write_bytes(completed.stderr)
        combined = completed.stdout.decode("utf-8", errors="replace") + completed.stderr.decode(
            "utf-8", errors="replace"
        )
        status = (
            "EXPECTED_REJECTION"
            if completed.returncode != 0 and token in combined
            else "INVALID_PROBE_RESULT"
        )
        report = {
            "schema_version": SCHEMA_VERSION,
            "report_kind": "utiki-negative-probe-transcript",
            "key": {
                name: request[name]
                for name in ("case_id", "obligation_id", "variant_id", "job_id", "target")
            },
            "candidate_sha": request["candidate_sha"],
            "environment": request["environment"],
            "mutation": request["mutation"],
            "child": {
                "kind": child_kind,
                "producer": producer,
                "producer_sha256": producer_digest,
                "command": command,
                "working_directory": str(child_working_directory),
            },
            "inputs": concrete_inputs,
            "outputs": [
                {"kind": "stdout", "path": str(stdout_path), "sha256": _sha256(stdout_path)},
                {"kind": "stderr", "path": str(stderr_path), "sha256": _sha256(stderr_path)},
            ],
            "observed_exit_code": completed.returncode,
            "rejection_token": token,
            "isolation_proof": isolation,
            "status": status,
        }
        report_path.write_text(
            json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        sys.stdout.buffer.write(completed.stdout)
        sys.stderr.buffer.write(completed.stderr)
        if status != "EXPECTED_REJECTION":
            sys.stderr.write("run_utiki_negative_probe: child did not produce the reviewed rejection\n")
            return 1
        return completed.returncode
    except (NegativeContractError, ProbeError, OSError, UnicodeError) as exc:
        sys.stderr.write(f"run_utiki_negative_probe: {exc}\n")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
